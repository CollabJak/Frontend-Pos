/**
 * Utility to convert raw permission keys (e.g., "category.view") into
 * human-readable Indonesian labels (e.g., "Melihat Kategori Produk").
 * Includes a fallback auto-formatting mechanism for unknown keys.
 */
export const getPermissionLabel = (permissionKey: string): string => {
  if (PERMISSION_LABELS[permissionKey]) {
    return PERMISSION_LABELS[permissionKey];
  }

  // Fallback formatter for unmapped permissions:
  // "custom_feature.view" => "Custom Feature (View)"
  const parts = permissionKey.split(".");
  if (parts.length === 2) {
    const feature = parts[0]
      .split("_")
      .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
      .join(" ");
    const action = parts[1].charAt(0).toUpperCase() + parts[1].slice(1);
    return `${action} ${feature}`;
  }

  return permissionKey;
};
